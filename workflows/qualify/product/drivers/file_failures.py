"""Opt-in public file CLI refusals in an invocation-owned private workspace."""
from pathlib import Path
import argparse
import base64
import hashlib
import os
import platform
import shutil
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'assets/scripts'))
from contracts import digest_file, read_json, require, write_json
from portable import command
import workspace_files


ASSERTIONS = {'expected-failure-observed', 'no-unowned-effects', 'actionable-result'}
PROBES = {'stale-write', 'escaped-write', 'linked-write'}


def selected(case):
    return (case['id'], case['scenario'], case['layer']) == ('files.workspace', 'failure', 'component')


def snapshot(root, canary):
    """Inspect only the three fixed generated entries, never follow the link."""
    require(set(path.name for path in root.iterdir()) == {'owned.txt', 'bystander.txt', 'linked.txt'},
            'Unexpected private workspace entry')
    link = root / 'linked.txt'
    require(link.is_symlink(), 'Generated link identity changed')
    result = {'linked.txt': os.readlink(link)}
    for path in [root / 'owned.txt', root / 'bystander.txt', canary]:
        require(path.is_file() and not path.is_symlink(), 'Generated regular fixture identity changed')
        result[str(path)] = digest_file(path)
    return result


def evaluate(facts):
    probes = facts.get('probes', {})
    exact_probes = set(probes) == PROBES
    refused = exact_probes and all(probe.get('normal_refusal') is True for probe in probes.values())
    unchanged = exact_probes and all(probe.get('snapshot_unchanged') is True for probe in probes.values())
    admitted = facts.get('positive_read_and_revision') is True
    return {
        'expected-failure-observed': admitted and refused,
        'no-unowned-effects': unchanged and facts.get('final_snapshot_unchanged') is True,
        'actionable-result': admitted and refused and facts.get('artifact_pins_unchanged') is True,
    }


def qualify(cli, workspace, environment, output, execute=command):
    root = output / 'file-workspace'
    root.mkdir(mode=0o700)
    owned = root / 'owned.txt'
    initial = b'\xef\xbb\xbfgenerated original\r\n'
    current = b'generated changed revision\r\n'
    owned.write_bytes(initial)
    (root / 'bystander.txt').write_bytes(b'generated bystander unchanged\r\n')
    canary = output / 'adjacent-canary.txt'
    canary.write_bytes(b'generated outside-root canary unchanged\r\n')
    (root / 'linked.txt').symlink_to(canary)
    evidence = []
    operations = []

    def invoke(name, action, path, **fields):
        request = output / (name + '.request.json')
        write_json(request, {'root': str(root), 'request': {
            'schema': 'dockpipe.files/v1', 'action': action, 'path': path, **fields,
        }})
        succeeded = execute(cli, ['files', '--request', str(request)], workspace,
                            environment, output, name)
        operations.append(name)
        evidence.append(request)
        evidence.extend(sorted((output / name).iterdir()))
        return succeeded

    read = invoke('positive-read', 'read', 'owned.txt')
    response = read_json(output / 'positive-read/driver.stdout') if read else {}
    initial_revision = hashlib.sha256(initial).hexdigest()
    facts = {'positive_read_and_revision': read and response.get('schema') == 'dockpipe.files/v1'
             and response.get('revision') == initial_revision
             and response.get('content') == base64.b64encode(initial).decode('ascii'), 'probes': {}}
    # Only a confirmed accessible public root/revision can qualify negative probes.
    if not facts['positive_read_and_revision']:
        return facts, evidence
    owned.write_bytes(current)
    before = snapshot(root, canary)
    replacement = base64.b64encode(b'must never publish rejected edit\n').decode('ascii')
    canary_revision = digest_file(canary)
    probes = [
        ('stale-write', 'owned.txt', initial_revision, {workspace_files.STALE_REVISION_DIAGNOSTIC}),
        ('escaped-write', '../adjacent-canary.txt', canary_revision, {workspace_files.OUTSIDE_ROOT_DIAGNOSTIC}),
        ('linked-write', 'linked.txt', canary_revision,
         {workspace_files.OUTSIDE_ROOT_DIAGNOSTIC, workspace_files.NOT_REGULAR_DIAGNOSTIC}),
    ]
    for name, path, revision, diagnostics in probes:
        succeeded = invoke(name, 'write', path, revision=revision, content=replacement)
        facts['probes'][name] = {
            'normal_refusal': not succeeded and workspace_files.expected_rejection(output, name, diagnostics),
            'snapshot_unchanged': snapshot(root, canary) == before,
        }
        if not all(facts['probes'][name].values()):
            break
    facts['final_snapshot_unchanged'] = snapshot(root, canary) == before
    facts['before_snapshot'] = before
    facts['after_snapshot'] = snapshot(root, canary)
    facts['operations'] = operations
    evidence.extend([owned, root / 'bystander.txt', canary])
    return facts, evidence


def emit(request, output, facts, evidence, status, reason):
    checks = evaluate(facts)
    cases = []
    for case in request['cases']:
        row = {name: case[name] for name in ['id', 'scenario', 'layer']}
        if selected(case):
            row.update(status=status, reason=reason, evidence=evidence,
                       assertions=[{'id': name, 'status': 'passed' if passed else 'failed', 'detail': reason}
                                   for name, passed in checks.items()] if status in ['passed', 'failed'] else [])
        else:
            row.update(status='blocked', reason='Only files.workspace/failure/component is implemented',
                       evidence=[], assertions=[])
        cases.append(row)
    result = {name: request[name] for name in ['run_id', 'plan_sha256', 'registry_sha256', 'target']}
    result.update(schema='dockpipe.product-integration.lane/v1', cases=cases, observed=facts)
    write_json(output / 'result.json', result)


def run(request, output):
    output.mkdir(mode=0o700, parents=True)
    cases = [case for case in request['cases'] if selected(case)]
    if not cases:
        emit(request, output, {}, [], 'blocked', 'No supported file failure case selected')
        return
    require(all(set(case['required_assertions']) == ASSERTIONS for case in cases), 'File failure assertion contract changed')
    target = request['target']
    require(platform.system() == 'Linux' and target['platform'] == 'linux-portable' and target['kind'] == 'local',
            'File refusal fixture requires the selected local Linux portable CLI')
    require(set(request['configuration']) == {'artifact'}, 'Select only the pinned CLI artifact')
    artifact = Path(request['configuration']['artifact'])
    require(artifact.is_absolute() and artifact.is_file() and not artifact.is_symlink(), 'Select an absolute regular CLI')
    require(digest_file(artifact) == target['artifact_sha256'], 'Selected CLI pin differs')
    cli = output / 'dockpipe'
    shutil.copyfile(artifact, cli)
    cli.chmod(0o700)
    require(digest_file(cli) == target['artifact_sha256'], 'Copied CLI pin differs')
    home = output / 'home'
    home.mkdir(mode=0o700)
    environment = {'PATH': '/usr/bin:/bin', 'HOME': str(home), 'LANG': 'C.UTF-8', 'LC_ALL': 'C.UTF-8',
                   'DOCKPIPE_GLOBAL_ROOT': str(home / 'global-store'),
                   'DOCKPIPE_SYSTEM_ROOT': str(home / 'system-store')}
    for name in ['config', 'cache', 'data', 'state']:
        directory = home / name
        directory.mkdir(mode=0o700)
        environment['XDG_' + name.upper() + '_HOME'] = str(directory)
    workspace = output / 'workspace'
    workspace.mkdir(mode=0o700)
    facts, paths = qualify(cli, workspace, environment, output)
    facts['artifact_pins_unchanged'] = (digest_file(cli) == target['artifact_sha256']
                                      and digest_file(artifact) == target['artifact_sha256'])
    write_json(output / 'observations.json', facts)
    paths.append(output / 'observations.json')
    evidence = [{'path': path.relative_to(output).as_posix(), 'sha256': digest_file(path)} for path in paths]
    require(len(evidence) <= 64, 'File failure evidence exceeds receipt bound')
    passed = all(evaluate(facts).values())
    emit(request, output, facts, evidence, 'passed' if passed else 'failed',
         'Actual public files CLI read, stale write, parent escape and generated symlink refusals with exact byte preservation')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--request', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    arguments = parser.parse_args()
    require(arguments.output.is_absolute() and not os.path.lexists(arguments.output), 'Select fresh absolute private output')
    request = read_json(arguments.request)
    require(request.get('schema') == 'dockpipe.product-integration.request/v1', 'Unknown product request')
    run(request, arguments.output)


if __name__ == '__main__':
    main()
