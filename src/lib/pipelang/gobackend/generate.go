func pipelangCheckedAddInt64(left, right int64) PipeLangArithmeticResult[int64] {
	const maximum = int64(9223372036854775807)
	const minimum = -maximum - 1
	if (right > 0 && left > maximum-right) || (right < 0 && left < minimum-right) {
		return PipeLangArithmeticResult[int64]{Error: PipeLangArithmeticOverflow}
	}
	return PipeLangArithmeticResult[int64]{OK: true, Value: left + right}
}

func pipelangCheckedSubtractInt64(left, right int64) PipeLangArithmeticResult[int64] {
	const maximum = int64(9223372036854775807)
	const minimum = -maximum - 1
	if (right < 0 && left > maximum+right) || (right > 0 && left < minimum+right) {
		return PipeLangArithmeticResult[int64]{Error: PipeLangArithmeticOverflow}
	}
	return PipeLangArithmeticResult[int64]{OK: true, Value: left - right}
}

func pipelangCheckedMultiplyInt64(left, right int64) PipeLangArithmeticResult[int64] {
	const maximum = int64(9223372036854775807)
	const minimum = -maximum - 1
	if left == 0 || right == 0 {
		return PipeLangArithmeticResult[int64]{OK: true}
	}
	if (left == minimum && right == -1) || (right == minimum && left == -1) {
		return PipeLangArithmeticResult[int64]{Error: PipeLangArithmeticOverflow}
	}
	value := left * right
	if value/right != left {
		return PipeLangArithmeticResult[int64]{Error: PipeLangArithmeticOverflow}
	}
	return PipeLangArithmeticResult[int64]{OK: true, Value: value}
}

