func isTextType(value coreir.Type) bool {
	return value.Kind == coreir.TypePrimitive && value.Primitive == coreir.PrimitiveString
}

func programNeedsTextSupport(functions []coreir.Function) bool {
	for _, function := range functions {
		if typeNeedsTextSupport(function.ReturnType) || expressionNeedsTextSupport(function.Body) {
			return true
		}
		needsBodyText := false
		coreir.WalkExpression(function.Body, func(expression coreir.Expr) bool {
			if typeNeedsTextSupport(expression.Type) {
				needsBodyText = true
				return false
			}
			return true
		})
		if needsBodyText {
			return true
		}
		for _, parameter := range function.Parameters {
			if typeNeedsTextSupport(parameter.Type) {
				return true
			}
		}
	}
	return false
}

func typeNeedsTextSupport(value coreir.Type) bool {
	if isTextType(value) {
		return true
	}
	if value.Record != nil {
		for _, field := range value.Record.Fields {
			if typeNeedsTextSupport(field.Type) {
				return true
			}
		}
	}
	if value.Optional != nil {
		return typeNeedsTextSupport(value.Optional.Value)
	}
	if value.List != nil {
		return typeNeedsTextSupport(value.List.Element)
	}
	if value.Result != nil {
		return typeNeedsTextSupport(value.Result.Success) || typeNeedsTextSupport(value.Result.Failure)
	}
	return false
}

