// Package gobackend lowers backend-neutral PipeLang Core IR into Go source.
// Its only PipeLang dependency is coreir, which makes a parser/AST-to-Go path
// unavailable to this backend.
package gobackend

import (
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"dockpipe/src/lib/pipelang/coreir"
)

const PackageName = "pipelanggenerated"

type Error struct {
	Code     string
	Function string
	Message  string
}

func (e *Error) Error() string {
	if e == nil {
		return ""
	}
	if e.Function == "" {
		return fmt.Sprintf("%s: %s", e.Code, e.Message)
	}
	return fmt.Sprintf("%s: function %s: %s", e.Code, e.Function, e.Message)
}

// Generate accepts Core IR only and returns deterministic, gofmt-formatted Go.
func Generate(program coreir.Program) ([]byte, error) {
	if (program.LanguageContract != coreir.LanguageContractV010 && program.LanguageContract != coreir.LanguageContractV020 && program.LanguageContract != coreir.LanguageContractV030 && program.LanguageContract != coreir.LanguageContractV040 && program.LanguageContract != coreir.LanguageContractV050 && program.LanguageContract != coreir.LanguageContractV060 && program.LanguageContract != coreir.LanguageContractV070 && program.LanguageContract != coreir.LanguageContractV080 && program.LanguageContract != coreir.LanguageContractV090 && program.LanguageContract != coreir.LanguageContractV100 && program.LanguageContract != coreir.LanguageContractV110 && program.LanguageContract != coreir.LanguageContractV120 && program.LanguageContract != coreir.LanguageContractV130 && program.LanguageContract != coreir.LanguageContractV140 && program.LanguageContract != coreir.LanguageContractV150 && program.LanguageContract != coreir.LanguageContractV160 && program.LanguageContract != coreir.LanguageContractV170 && program.LanguageContract != coreir.LanguageContractV180 && program.LanguageContract != coreir.LanguageContractV190 && program.LanguageContract != coreir.LanguageContractV200 && program.LanguageContract != coreir.LanguageContractV210 && program.LanguageContract != coreir.LanguageContractV220 && program.LanguageContract != coreir.LanguageContractV240 && program.LanguageContract != coreir.LanguageContractV230) || program.CompilerContract != coreir.CompilerContractV1 {
		return nil, &Error{Code: "PLGO0001", Message: fmt.Sprintf("unsupported Core IR contracts language=%q compiler=%q", program.LanguageContract, program.CompilerContract)}
	}
	functions := append([]coreir.Function(nil), program.Functions...)
	sort.SliceStable(functions, func(i, j int) bool {
		left, right := identityKey(functions[i].Identity), identityKey(functions[j].Identity)
		if left != right {
			return left < right
		}
		return functions[i].Name < functions[j].Name
	})
	for _, function := range functions {
		if err := coreir.ValidateFunction(function); err != nil {
			return nil, backendError(function, "PLGO0001", err.Error())
		}
	}
	var out strings.Builder
	out.WriteString("// Code generated by PipeLang pipelang.compiler.v1; DO NOT EDIT.\n")
	out.WriteString("package " + PackageName + "\n\n")
	needsText := programNeedsTextSupport(functions)
	needsCaseFoldedText := programNeedsCaseFoldedText(functions)
	needsOptional := programNeedsOptionalSupport(functions)
	needsOptionalDefault := programNeedsOptionalDefault(functions)
	needsRecordOptional := programNeedsRecordOptionalSupport(functions)
	needsList := programNeedsListSupport(functions)
	needsListCount := programNeedsListCount(functions)
	needsListAppend := programNeedsListAppend(functions)
	needsListAt := programNeedsListAt(functions)
	needsListFindByText := programNeedsListFindByText(functions)
	needsListFilterByText := programNeedsListFilterByText(functions)
	needsListFilterContainsCaseFolded := programNeedsListFilterContainsCaseFolded(functions)
	needsSnapshotResult := programNeedsSnapshotResult(functions)
	optionalTypeName := optionalGoTypeName(functions)
	if needsOptional && program.LanguageContract != coreir.LanguageContractV130 && program.LanguageContract != coreir.LanguageContractV140 && program.LanguageContract != coreir.LanguageContractV150 && program.LanguageContract != coreir.LanguageContractV160 && program.LanguageContract != coreir.LanguageContractV170 && program.LanguageContract != coreir.LanguageContractV180 && program.LanguageContract != coreir.LanguageContractV190 && program.LanguageContract != coreir.LanguageContractV200 && program.LanguageContract != coreir.LanguageContractV210 && program.LanguageContract != coreir.LanguageContractV220 && program.LanguageContract != coreir.LanguageContractV240 && program.LanguageContract != coreir.LanguageContractV230 {
		return nil, &Error{Code: "PLGO0001", Message: fmt.Sprintf("primitive Optional Core requires language contract %q", coreir.LanguageContractV130)}
	}
	if needsOptionalDefault && program.LanguageContract != coreir.LanguageContractV140 && program.LanguageContract != coreir.LanguageContractV150 && program.LanguageContract != coreir.LanguageContractV160 && program.LanguageContract != coreir.LanguageContractV170 && program.LanguageContract != coreir.LanguageContractV180 && program.LanguageContract != coreir.LanguageContractV190 && program.LanguageContract != coreir.LanguageContractV200 && program.LanguageContract != coreir.LanguageContractV210 && program.LanguageContract != coreir.LanguageContractV220 && program.LanguageContract != coreir.LanguageContractV240 && program.LanguageContract != coreir.LanguageContractV230 {
		return nil, &Error{Code: "PLGO0001", Message: fmt.Sprintf("primitive Optional defaulting Core requires language contract %q", coreir.LanguageContractV140)}
	}
	if needsRecordOptional && program.LanguageContract != coreir.LanguageContractV180 && program.LanguageContract != coreir.LanguageContractV190 && program.LanguageContract != coreir.LanguageContractV200 && program.LanguageContract != coreir.LanguageContractV210 && program.LanguageContract != coreir.LanguageContractV220 && program.LanguageContract != coreir.LanguageContractV240 && program.LanguageContract != coreir.LanguageContractV230 {
		return nil, &Error{Code: "PLGO0001", Message: fmt.Sprintf("primitive-record Optional Core requires language contract %q", coreir.LanguageContractV180)}
	}
	if needsList && program.LanguageContract != coreir.LanguageContractV150 && program.LanguageContract != coreir.LanguageContractV160 && program.LanguageContract != coreir.LanguageContractV170 && program.LanguageContract != coreir.LanguageContractV180 && program.LanguageContract != coreir.LanguageContractV190 && program.LanguageContract != coreir.LanguageContractV200 && program.LanguageContract != coreir.LanguageContractV210 && program.LanguageContract != coreir.LanguageContractV220 && program.LanguageContract != coreir.LanguageContractV240 && program.LanguageContract != coreir.LanguageContractV230 {
		return nil, &Error{Code: "PLGO0001", Message: fmt.Sprintf("record-list Core requires language contract %q", coreir.LanguageContractV150)}
	}
	if needsListCount && program.LanguageContract != coreir.LanguageContractV160 && program.LanguageContract != coreir.LanguageContractV170 && program.LanguageContract != coreir.LanguageContractV180 && program.LanguageContract != coreir.LanguageContractV190 && program.LanguageContract != coreir.LanguageContractV200 && program.LanguageContract != coreir.LanguageContractV210 && program.LanguageContract != coreir.LanguageContractV220 && program.LanguageContract != coreir.LanguageContractV240 && program.LanguageContract != coreir.LanguageContractV230 {
		return nil, &Error{Code: "PLGO0001", Message: fmt.Sprintf("record-list count Core requires language contract %q", coreir.LanguageContractV160)}
	}
	if needsListAppend && program.LanguageContract != coreir.LanguageContractV170 && program.LanguageContract != coreir.LanguageContractV180 && program.LanguageContract != coreir.LanguageContractV190 && program.LanguageContract != coreir.LanguageContractV200 && program.LanguageContract != coreir.LanguageContractV210 && program.LanguageContract != coreir.LanguageContractV220 && program.LanguageContract != coreir.LanguageContractV240 && program.LanguageContract != coreir.LanguageContractV230 {
		return nil, &Error{Code: "PLGO0001", Message: fmt.Sprintf("record-list append Core requires language contract %q", coreir.LanguageContractV170)}
	}
	if needsSnapshotResult && program.LanguageContract != coreir.LanguageContractV190 && program.LanguageContract != coreir.LanguageContractV200 && program.LanguageContract != coreir.LanguageContractV210 && program.LanguageContract != coreir.LanguageContractV220 && program.LanguageContract != coreir.LanguageContractV240 && program.LanguageContract != coreir.LanguageContractV230 {
		return nil, &Error{Code: "PLGO0001", Message: fmt.Sprintf("snapshot Result Core requires language contract %q", coreir.LanguageContractV190)}
	}
	if needsListAt && program.LanguageContract != coreir.LanguageContractV200 && program.LanguageContract != coreir.LanguageContractV210 && program.LanguageContract != coreir.LanguageContractV220 && program.LanguageContract != coreir.LanguageContractV240 && program.LanguageContract != coreir.LanguageContractV230 {
		return nil, &Error{Code: "PLGO0001", Message: fmt.Sprintf("record-list at Core requires language contract %q", coreir.LanguageContractV200)}
	}
	if needsListFindByText && program.LanguageContract != coreir.LanguageContractV210 && program.LanguageContract != coreir.LanguageContractV220 && program.LanguageContract != coreir.LanguageContractV240 && program.LanguageContract != coreir.LanguageContractV230 {
		return nil, &Error{Code: "PLGO0001", Message: fmt.Sprintf("record-list find_by Core requires language contract %q", coreir.LanguageContractV210)}
	}
	if needsListFilterByText && program.LanguageContract != coreir.LanguageContractV220 && program.LanguageContract != coreir.LanguageContractV240 && program.LanguageContract != coreir.LanguageContractV230 {
		return nil, &Error{Code: "PLGO0001", Message: fmt.Sprintf("record-list filter_by Core requires language contract %q", coreir.LanguageContractV220)}
	}
	if needsCaseFoldedText && program.LanguageContract != coreir.LanguageContractV240 && program.LanguageContract != coreir.LanguageContractV230 {
		return nil, &Error{Code: "PLGO0001", Message: fmt.Sprintf("contains_casefolded Core requires language contract %q", coreir.LanguageContractV230)}
	}
	if needsListFilterContainsCaseFolded && program.LanguageContract != coreir.LanguageContractV240 {
		return nil, &Error{Code: "PLGO0001", Message: fmt.Sprintf("record-list filter_contains_casefolded Core requires language contract %q", coreir.LanguageContractV240)}
	}
	if needsText {
		if needsCaseFoldedText {
			out.WriteString("import (\n\t\"strings\"\n\t\"unicode/utf8\"\n)\n\n")
		} else {
			out.WriteString("import \"unicode/utf8\"\n\n")
		}
		emitTextSupport(&out, needsCaseFoldedText)
	}
	if programNeedsArithmeticResult(functions) {
		emitArithmeticSupport(&out)
	}
	records, err := collectRecordTypes(functions)
	if err != nil {
		return nil, &Error{Code: "PLGO0001", Message: err.Error()}
	}
	if needsOptional {
		emitOptionalSupport(&out, needsText, needsOptionalDefault, needsRecordOptional, optionalTypeName, records)
	}
	for _, record := range records {
		emitRecordType(&out, record, programConstructsRecord(functions, record), optionalTypeName)
	}
	lists, err := collectListTypes(functions)
	if err != nil {
		return nil, &Error{Code: "PLGO0001", Message: err.Error()}
	}
	for _, list := range lists {
		emitListSupport(&out, list, programAppendsList(functions, list), programIndexesList(functions, list), programFindsListByText(functions, list), programFiltersListByText(functions, list), programFiltersListContainsCaseFolded(functions, list), optionalTypeName)
	}
	results, err := collectSnapshotResultTypes(functions)
	if err != nil {
		return nil, &Error{Code: "PLGO0001", Message: err.Error()}
	}
	if len(results) > 0 {
		emitSnapshotResultType(&out)
		for _, result := range results {
			emitSnapshotResultSupport(&out, result)
		}
	}
	seen := map[string]string{}
	seenIdentities := map[string]struct{}{}
	for _, function := range functions {
		identity := identityKey(function.Identity)
		if function.Identity.PackageID == "" || function.Identity.Path == "" {
			return nil, backendError(function, "PLGO0001", "function has no semantic identity")
		}
		if _, duplicate := seenIdentities[identity]; duplicate {
			return nil, backendError(function, "PLGO0002", "duplicate semantic function identity")
		}
		seenIdentities[identity] = struct{}{}
		if err := coreir.ValidateFunction(function); err != nil {
			return nil, backendError(function, "PLGO0001", err.Error())
		}
		name := FunctionName(function)
		if previous, ok := seen[name]; ok {
			return nil, backendError(function, "PLGO0002", fmt.Sprintf("Go name %q collides with %s", name, previous))
		}
		seen[name] = identity
		if err := emitFunction(&out, name, function, optionalTypeName); err != nil {
			return nil, err
		}
	}
	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		return nil, &Error{Code: "PLGO0003", Message: fmt.Sprintf("format generated Go: %v", err)}
	}
	return formatted, nil
}

func FunctionName(function coreir.Function) string {
	name := strings.TrimSpace(function.Name)
	if name == "" {
		name = finalPathSegment(function.Identity.Path)
	}
	return "PipeLang" + exportedIdentifier(name)
}

func emitFunction(out *strings.Builder, name string, function coreir.Function, optionalTypeName string) error {
	result, err := goType(function.ReturnType, optionalTypeName)
	if err != nil {
		return backendError(function, "PLGO0001", err.Error())
	}
	fmt.Fprintf(out, "func %s(", name)
	for index, parameter := range function.Parameters {
		if parameter.Position != index {
			return backendError(function, "PLGO0001", "parameters are not in normalized position order")
		}
		parameterType, err := goType(parameter.Type, optionalTypeName)
		if err != nil {
			return backendError(function, "PLGO0001", err.Error())
		}
		if index > 0 {
			out.WriteString(", ")
		}
		fmt.Fprintf(out, "p%d %s", index, parameterType)
	}
	fmt.Fprintf(out, ") %s {\n", result)
	for index, parameter := range function.Parameters {
		if parameter.Type.Kind == coreir.TypeRecord {
			fmt.Fprintf(out, "\t%s(p%d)\n", recordValidationName(parameter.Type), index)
		}
		if parameter.Type.Kind == coreir.TypeOptional {
			fmt.Fprintf(out, "\tpipelangValidateOptional(p%d)\n", index)
		}
		if parameter.Type.Kind == coreir.TypeList {
			fmt.Fprintf(out, "\t%s(p%d)\n", listValidationName(parameter.Type), index)
		}
		if isSnapshotResultType(parameter.Type) {
			fmt.Fprintf(out, "\t%s(p%d)\n", snapshotResultValidationName(parameter.Type), index)
		}
	}
	out.WriteString("\treturn ")
	body, err := emitExpr(function.Body, function.Parameters, optionalTypeName)
	if err != nil {
		return backendError(function, "PLGO0001", err.Error())
	}
	out.WriteString(body)
	out.WriteString("\n}\n\n")
	return nil
}

func emitExpr(expr coreir.Expr, parameters []coreir.Parameter, optionalTypeName string) (string, error) {
	switch expr.Kind {
	case coreir.ExprLiteral:
		if expr.Literal == nil {
			return "", fmt.Errorf("literal node has no value")
		}
		return emitLiteral(expr.Type, *expr.Literal)
	case coreir.ExprReference:
		if expr.Parameter == nil || *expr.Parameter < 0 || *expr.Parameter >= len(parameters) {
			return "", fmt.Errorf("reference has invalid parameter position")
		}
		if expr.Type.Kind == coreir.TypeList {
			return fmt.Sprintf("%s(p%d)", listCloneName(expr.Type), *expr.Parameter), nil
		}
		if isSnapshotResultType(expr.Type) {
			return fmt.Sprintf("%s(p%d)", snapshotResultCloneName(expr.Type), *expr.Parameter), nil
		}
		return fmt.Sprintf("p%d", *expr.Parameter), nil
	case coreir.ExprUnary:
		if expr.Unary == nil || expr.Unary.Operand == nil {
			return "", fmt.Errorf("unary node is incomplete")
		}
		operand, err := emitExpr(*expr.Unary.Operand, parameters, optionalTypeName)
		if err != nil {
			return "", err
		}
		if expr.Unary.Operator == coreir.OperatorNegate {
			return "pipelangCheckedNegateInt64(" + operand + ")", nil
		}
		op, ok := mapUnaryOperator(expr.Unary.Operator)
		if !ok {
			return "", fmt.Errorf("unsupported unary operator %q", expr.Unary.Operator)
		}
		return "(" + op + operand + ")", nil
	case coreir.ExprBinary:
		if expr.Binary == nil || expr.Binary.Left == nil || expr.Binary.Right == nil {
			return "", fmt.Errorf("binary node is incomplete")
		}
		switch expr.Binary.Operator {
		case coreir.OperatorAnd, coreir.OperatorOr:
			return "", fmt.Errorf("operator %q is outside the step-7a Go capability slice", expr.Binary.Operator)
		}
		left, err := emitExpr(*expr.Binary.Left, parameters, optionalTypeName)
		if err != nil {
			return "", err
		}
		right, err := emitExpr(*expr.Binary.Right, parameters, optionalTypeName)
		if err != nil {
			return "", err
		}
		if isTextType(expr.Binary.Left.Type) && isTextType(expr.Binary.Right.Type) {
			switch expr.Binary.Operator {
			case coreir.OperatorAdd:
				return "pipelangConcatText(" + left + ", " + right + ")", nil
			case coreir.OperatorEqual:
				return "(pipelangCompareOrdinalText(" + left + ", " + right + ") == 0)", nil
			case coreir.OperatorNotEqual:
				return "(pipelangCompareOrdinalText(" + left + ", " + right + ") != 0)", nil
			case coreir.OperatorLessThan:
				return "(pipelangCompareOrdinalText(" + left + ", " + right + ") < 0)", nil
			case coreir.OperatorLessOrEqual:
				return "(pipelangCompareOrdinalText(" + left + ", " + right + ") <= 0)", nil
			case coreir.OperatorGreaterThan:
				return "(pipelangCompareOrdinalText(" + left + ", " + right + ") > 0)", nil
			case coreir.OperatorGreaterOrEqual:
				return "(pipelangCompareOrdinalText(" + left + ", " + right + ") >= 0)", nil
			}
		}
		if expr.Type.Kind == coreir.TypeResult {
			helper, ok := arithmeticHelperName(expr.Binary.Operator)
			if !ok {
				return "", fmt.Errorf("unsupported checked arithmetic operator %q", expr.Binary.Operator)
			}
			return helper + "(" + left + ", " + right + ")", nil
		}
		if requiresEqualOperands(expr.Binary.Operator) && !coreir.TypeEqual(expr.Binary.Left.Type, expr.Binary.Right.Type) {
			return "", fmt.Errorf("operator %q has mismatched Core operand types", expr.Binary.Operator)
		}
		op, ok := mapBinaryOperator(expr.Binary.Operator)
		if !ok {
			return "", fmt.Errorf("unsupported binary operator %q", expr.Binary.Operator)
		}
		return "(" + left + " " + op + " " + right + ")", nil
	case coreir.ExprTextContainsCaseFolded:
		if expr.TextContains == nil || expr.TextContains.Value == nil || expr.TextContains.Query == nil {
			return "", fmt.Errorf("contains_casefolded expression is incomplete")
		}
		value, err := emitExpr(*expr.TextContains.Value, parameters, optionalTypeName)
		if err != nil {
			return "", err
		}
		query, err := emitExpr(*expr.TextContains.Query, parameters, optionalTypeName)
		if err != nil {
			return "", err
		}
		return "pipelangContainsCaseFoldedText(" + value + ", " + query + ")", nil
	case coreir.ExprFieldProjection:
		if expr.Field == nil || expr.Field.Receiver == nil {
			return "", fmt.Errorf("field projection is incomplete")
		}
		receiverType := expr.Field.Receiver.Type
		if receiverType.Kind != coreir.TypeRecord || receiverType.Record == nil || expr.Field.Position < 0 || expr.Field.Position >= len(receiverType.Record.Fields) {
			return "", fmt.Errorf("field projection has an invalid record schema or position")
		}
		receiver, err := emitExpr(*expr.Field.Receiver, parameters, optionalTypeName)
		if err != nil {
			return "", err
		}
		return receiver + "." + recordGoFieldNames(receiverType)[expr.Field.Position], nil
	case coreir.ExprRecordConstruct:
		if expr.Record == nil || expr.Type.Kind != coreir.TypeRecord || expr.Type.Record == nil || len(expr.Record.Fields) != len(expr.Type.Record.Fields) {
			return "", fmt.Errorf("record construction is incomplete or does not match its schema")
		}
		arguments := make([]string, 0, len(expr.Record.Fields))
		for position, initialized := range expr.Record.Fields {
			if initialized.Value == nil || initialized.Position != position {
				return "", fmt.Errorf("record construction field %d is incomplete or out of order", position)
			}
			value, err := emitExpr(*initialized.Value, parameters, optionalTypeName)
			if err != nil {
				return "", err
			}
			arguments = append(arguments, value)
		}
		return recordConstructionName(expr.Type) + "(" + strings.Join(arguments, ", ") + ")", nil
	case coreir.ExprOptionalSome:
		if expr.Some == nil || expr.Some.Value == nil || expr.Type.Kind != coreir.TypeOptional {
			return "", fmt.Errorf("optional some expression is incomplete")
		}
		value, err := emitExpr(*expr.Some.Value, parameters, optionalTypeName)
		if err != nil {
			return "", err
		}
		return "pipelangSomeValue(" + value + ")", nil
	case coreir.ExprOptionalNone:
		if expr.None == nil || expr.Type.Kind != coreir.TypeOptional || expr.Type.Optional == nil {
			return "", fmt.Errorf("optional none expression is incomplete")
		}
		valueType, err := goType(expr.Type.Optional.Value, optionalTypeName)
		if err != nil {
			return "", err
		}
		return "pipelangNoneValue[" + valueType + "]()", nil
	case coreir.ExprOptionalHasValue:
		if expr.HasValue == nil || expr.HasValue.Value == nil {
			return "", fmt.Errorf("optional has_value expression is incomplete")
		}
		value, err := emitExpr(*expr.HasValue.Value, parameters, optionalTypeName)
		if err != nil {
			return "", err
		}
		return "pipelangHasValue(" + value + ")", nil
	case coreir.ExprOptionalValueOr:
		if expr.ValueOr == nil || expr.ValueOr.Value == nil || expr.ValueOr.Fallback == nil {
			return "", fmt.Errorf("optional value_or expression is incomplete")
		}
		value, err := emitExpr(*expr.ValueOr.Value, parameters, optionalTypeName)
		if err != nil {
			return "", err
		}
		fallback, err := emitExpr(*expr.ValueOr.Fallback, parameters, optionalTypeName)
		if err != nil {
			return "", err
		}
		return "pipelangValueOr(" + value + ", " + fallback + ")", nil
	case coreir.ExprListEmpty:
		if expr.ListEmpty == nil || expr.Type.Kind != coreir.TypeList {
			return "", fmt.Errorf("list empty expression is incomplete")
		}
		return listEmptyName(expr.Type) + "()", nil
	case coreir.ExprListSingleton:
		if expr.ListOne == nil || expr.ListOne.Value == nil || expr.Type.Kind != coreir.TypeList {
			return "", fmt.Errorf("list singleton expression is incomplete")
		}
		value, err := emitExpr(*expr.ListOne.Value, parameters, optionalTypeName)
		if err != nil {
			return "", err
		}
		return listSingletonName(expr.Type) + "(" + value + ")", nil
	case coreir.ExprListCount:
		if expr.ListCount == nil || expr.ListCount.Value == nil || expr.ListCount.Value.Kind != coreir.ExprReference || expr.ListCount.Value.Parameter == nil {
			return "", fmt.Errorf("list count expression is incomplete")
		}
		return fmt.Sprintf("int64(len(p%d))", *expr.ListCount.Value.Parameter), nil
	case coreir.ExprListAppend:
		if expr.ListAppend == nil || expr.ListAppend.Values == nil || expr.ListAppend.Value == nil || expr.ListAppend.Values.Kind != coreir.ExprReference || expr.ListAppend.Values.Parameter == nil || expr.ListAppend.Value.Kind != coreir.ExprReference || expr.ListAppend.Value.Parameter == nil {
			return "", fmt.Errorf("list append expression is incomplete")
		}
		return fmt.Sprintf("%s(p%d, p%d)", listAppendName(expr.Type), *expr.ListAppend.Values.Parameter, *expr.ListAppend.Value.Parameter), nil
	case coreir.ExprListAt:
		if expr.ListAt == nil || expr.ListAt.Values == nil || expr.ListAt.Index == nil || expr.ListAt.Values.Kind != coreir.ExprReference || expr.ListAt.Values.Parameter == nil || expr.ListAt.Index.Kind != coreir.ExprReference || expr.ListAt.Index.Parameter == nil || expr.ListAt.Values.Type.Kind != coreir.TypeList {
			return "", fmt.Errorf("list at expression is incomplete")
		}
		return fmt.Sprintf("%s(p%d, p%d)", listAtName(expr.ListAt.Values.Type), *expr.ListAt.Values.Parameter, *expr.ListAt.Index.Parameter), nil
	case coreir.ExprListFindByText:
		if expr.ListFind == nil || expr.ListFind.Values == nil || expr.ListFind.Key == nil || expr.ListFind.Values.Kind != coreir.ExprReference || expr.ListFind.Values.Parameter == nil || expr.ListFind.Key.Kind != coreir.ExprReference || expr.ListFind.Key.Parameter == nil || expr.ListFind.Values.Type.Kind != coreir.TypeList {
			return "", fmt.Errorf("list find_by expression is incomplete")
		}
		return fmt.Sprintf("%s(p%d, p%d)", listFindByTextName(expr.ListFind.Values.Type, *expr.ListFind), *expr.ListFind.Values.Parameter, *expr.ListFind.Key.Parameter), nil
	case coreir.ExprListFilterByText:
		if expr.ListFilter == nil || expr.ListFilter.Values == nil || expr.ListFilter.Key == nil || expr.ListFilter.Values.Kind != coreir.ExprReference || expr.ListFilter.Values.Parameter == nil || expr.ListFilter.Key.Kind != coreir.ExprReference || expr.ListFilter.Key.Parameter == nil || expr.ListFilter.Values.Type.Kind != coreir.TypeList {
			return "", fmt.Errorf("list filter_by expression is incomplete")
		}
		return fmt.Sprintf("%s(p%d, p%d)", listFilterByTextName(expr.ListFilter.Values.Type, *expr.ListFilter), *expr.ListFilter.Values.Parameter, *expr.ListFilter.Key.Parameter), nil
	case coreir.ExprListFilterContainsCaseFolded:
		filter := expr.ListFilterContainsCaseFolded
		if filter == nil || filter.Values == nil || filter.Query == nil || filter.Values.Kind != coreir.ExprReference || filter.Values.Parameter == nil || filter.Query.Kind != coreir.ExprReference || filter.Query.Parameter == nil || filter.Values.Type.Kind != coreir.TypeList {
			return "", fmt.Errorf("list filter_contains_casefolded expression is incomplete")
		}
		return fmt.Sprintf("%s(p%d, p%d)", listFilterContainsCaseFoldedName(filter.Values.Type, *filter), *filter.Values.Parameter, *filter.Query.Parameter), nil
	case coreir.ExprResultOK:
		if expr.ResultOK == nil || expr.ResultOK.Value == nil || !isSnapshotResultType(expr.Type) {
			return "", fmt.Errorf("result ok expression is incomplete")
		}
		value, err := emitExpr(*expr.ResultOK.Value, parameters, optionalTypeName)
		if err != nil {
			return "", err
		}
		return snapshotResultOKName(expr.Type) + "(" + value + ")", nil
	case coreir.ExprResultErr:
		if expr.ResultErr == nil || expr.ResultErr.Error == nil || !isSnapshotResultType(expr.Type) {
			return "", fmt.Errorf("result err expression is incomplete")
		}
		failure, err := emitExpr(*expr.ResultErr.Error, parameters, optionalTypeName)
		if err != nil {
			return "", err
		}
		return snapshotResultErrName(expr.Type) + "(" + failure + ")", nil
	case coreir.ExprResultIsOK:
		if expr.ResultIsOK == nil || expr.ResultIsOK.Value == nil || !isSnapshotResultType(expr.ResultIsOK.Value.Type) {
			return "", fmt.Errorf("result is_ok expression is incomplete")
		}
		value, err := emitExpr(*expr.ResultIsOK.Value, parameters, optionalTypeName)
		if err != nil {
			return "", err
		}
		return snapshotResultIsOKName(expr.ResultIsOK.Value.Type) + "(" + value + ")", nil
	case coreir.ExprResultSuccessOr:
		if expr.SuccessOr == nil || expr.SuccessOr.Value == nil || expr.SuccessOr.Fallback == nil || !isSnapshotResultType(expr.SuccessOr.Value.Type) {
			return "", fmt.Errorf("result success_or expression is incomplete")
		}
		value, err := emitExpr(*expr.SuccessOr.Value, parameters, optionalTypeName)
		if err != nil {
			return "", err
		}
		fallback, err := emitExpr(*expr.SuccessOr.Fallback, parameters, optionalTypeName)
		if err != nil {
			return "", err
		}
		return snapshotResultSuccessOrName(expr.SuccessOr.Value.Type) + "(" + value + ", " + fallback + ")", nil
	case coreir.ExprResultFailureOr:
		if expr.FailureOr == nil || expr.FailureOr.Value == nil || expr.FailureOr.Fallback == nil || !isSnapshotResultType(expr.FailureOr.Value.Type) {
			return "", fmt.Errorf("result failure_or expression is incomplete")
		}
		value, err := emitExpr(*expr.FailureOr.Value, parameters, optionalTypeName)
		if err != nil {
			return "", err
		}
		fallback, err := emitExpr(*expr.FailureOr.Fallback, parameters, optionalTypeName)
		if err != nil {
			return "", err
		}
		return snapshotResultFailureOrName(expr.FailureOr.Value.Type) + "(" + value + ", " + fallback + ")", nil
	default:
		return "", fmt.Errorf("unsupported expression kind %q", expr.Kind)
	}
}

func emitLiteral(typ coreir.Type, literal coreir.Literal) (string, error) {
	if typ.Kind == coreir.TypeNumeric {
		if typ.Numeric == nil {
			return "", fmt.Errorf("numeric literal type has no representation")
		}
		switch {
		case typ.Numeric.Representation == coreir.NumericInteger && typ.Numeric.Bits == 64 && typ.Numeric.Signed:
			return fmt.Sprintf("int64(%d)", literal.Int), nil
		case typ.Numeric.Representation == coreir.NumericBinaryFloat && typ.Numeric.Bits == 64 && !typ.Numeric.Signed:
			return "float64(" + strconv.FormatFloat(literal.Float, 'g', -1, 64) + ")", nil
		default:
			return "", fmt.Errorf("unsupported numeric literal representation %q/%d", typ.Numeric.Representation, typ.Numeric.Bits)
		}
	}
	if typ.Kind != coreir.TypePrimitive {
		return "", fmt.Errorf("literal type %q is unsupported", typ.Kind)
	}
	switch typ.Primitive {
	case coreir.PrimitiveString:
		return strconv.Quote(literal.String), nil
	case coreir.PrimitiveBool:
		return strconv.FormatBool(literal.Bool), nil
	default:
		return "", fmt.Errorf("unsupported primitive literal type %q", typ.Primitive)
	}
}

func goType(typ coreir.Type, optionalTypeName string) (string, error) {
	if typ.Kind == coreir.TypeList {
		if typ.List == nil || typ.List.Element.Kind != coreir.TypeRecord {
			return "", fmt.Errorf("Go list backend requires one record element type")
		}
		element, err := goType(typ.List.Element, optionalTypeName)
		if err != nil {
			return "", err
		}
		return "[]" + element, nil
	}
	if typ.Kind == coreir.TypeOptional {
		if typ.Optional == nil {
			return "", fmt.Errorf("Go Optional backend requires a value type")
		}
		value, err := goType(typ.Optional.Value, optionalTypeName)
		if err != nil {
			return "", err
		}
		return optionalTypeName + "[" + value + "]", nil
	}
	if typ.Kind == coreir.TypeRecord {
		if typ.Record == nil || typ.Identity == nil || typ.Identity.PackageID == "" || typ.Identity.Path == "" {
			return "", fmt.Errorf("Go record backend requires an identified record schema")
		}
		return recordGoTypeName(typ), nil
	}
	if typ.Kind == coreir.TypeResult {
		if typ.Result == nil {
			return "", fmt.Errorf("Go Result backend requires success and failure types")
		}
		success, err := goType(typ.Result.Success, optionalTypeName)
		if err != nil {
			return "", err
		}
		if typ.Result.Failure.Kind == coreir.TypeArithmeticError {
			return "PipeLangArithmeticResult[" + success + "]", nil
		}
		if !isSnapshotResultType(typ) {
			return "", fmt.Errorf("Go Result backend supports only arithmetic and snapshot Result shapes")
		}
		failure, err := goType(typ.Result.Failure, optionalTypeName)
		if err != nil {
			return "", err
		}
		return "PipeLangResult[" + success + ", " + failure + "]", nil
	}
	if typ.Kind == coreir.TypeNumeric {
		if typ.Numeric == nil {
			return "", fmt.Errorf("numeric Core type has no representation")
		}
		switch {
		case typ.Numeric.Representation == coreir.NumericInteger && typ.Numeric.Bits == 64 && typ.Numeric.Signed:
			return "int64", nil
		case typ.Numeric.Representation == coreir.NumericBinaryFloat && typ.Numeric.Bits == 64 && !typ.Numeric.Signed:
			return "float64", nil
		default:
			return "", fmt.Errorf("Go checked-arithmetic backend does not support numeric representation %q/%d", typ.Numeric.Representation, typ.Numeric.Bits)
		}
	}
	if typ.Kind != coreir.TypePrimitive {
		return "", fmt.Errorf("Go checked-arithmetic backend supports primitive, fixed numeric, and arithmetic Result types only, got %q", typ.Kind)
	}
	switch typ.Primitive {
	case coreir.PrimitiveString:
		return "string", nil
	case coreir.PrimitiveBool:
		return "bool", nil
	default:
		return "", fmt.Errorf("unsupported primitive type %q", typ.Primitive)
	}
}

