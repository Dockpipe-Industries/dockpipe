func backendError(function coreir.Function, code, message string) error {
	return &Error{Code: code, Function: identityKey(function.Identity), Message: message}
}

func identityKey(identity coreir.SemanticIdentity) string {
	return identity.PackageID + ":" + identity.Path
}

func finalPathSegment(path string) string {
	if index := strings.LastIndexByte(path, '.'); index >= 0 {
		return path[index+1:]
	}
	return path
}

func exportedIdentifier(value string) string {
	var out strings.Builder
	upperNext := true
	for _, r := range value {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			upperNext = true
			continue
		}
		if out.Len() == 0 && unicode.IsDigit(r) {
			out.WriteRune('X')
		}
		if upperNext {
			r = unicode.ToUpper(r)
			upperNext = false
		}
		out.WriteRune(r)
	}
	if out.Len() == 0 {
		return "Function"
	}
	return out.String()
}
