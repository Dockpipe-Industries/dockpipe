func identityKey(identity coreir.SemanticIdentity) string {
	return identity.PackageID + ":" + identity.Path
}

func finalPathSegment(path string) string {
	if index := strings.LastIndexByte(path, '.'); index >= 0 {
		return path[index+1:]
	}
	return path
}

func exportedIdentifier(value string) string {
	var out strings.Builder
	upperNext := true
	for _, r := range value {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			upperNext = true
			continue
		}
		if out.Len() == 0 && unicode.IsDigit(r) {
			out.WriteRune('X')
		}
		if upperNext {
			r = unicode.ToUpper(r)
			upperNext = false
		}
		out.WriteRune(r)
	}
	if out.Len() == 0 {
		return "Function"
	}
	return out.String()
}

func sortedFunctions(input []coreir.Function) []coreir.Function {
	functions := append([]coreir.Function(nil), input...)
	sort.SliceStable(functions, func(i, j int) bool {
		left, right := identityKey(functions[i].Identity), identityKey(functions[j].Identity)
		if left != right {
			return left < right
		}
		return functions[i].Name < functions[j].Name
	})
	return functions
}
